const DEFAULT_CENTER: [number, number] = [118.78, 32.04]  // 南京

async function renderMap() {
  if (!mapDiv.value) return
  try {
    const AMap = await loadAMap()
    // 不在 URL 里挂 plugin,改用 AMap.plugin 异步加载,失败不影响基础地图
    AMap.plugin(['AMap.Geocoder', 'AMap.Marker'], () => {
      geocoder = new AMap.Geocoder({ city: '全国', batch: true })
      console.log('[HomeMap] Geocoder+Marker plugins ready')
    })
    mapInstance = new AMap.Map(mapDiv.value, {
      zoom: 11,
      center: DEFAULT_CENTER,
      mapStyle: 'amap://styles/light',
    })
    console.log('[HomeMap] AMap 基础地图初始化完成')
    if (props.destination) locate(props.destination)
  } catch (e: any) {
    console.error('[HomeMap] 地图加载失败:', e)
    loadError.value = e.message || String(e)
  }
}

function locate(city: string) {
  if (!mapInstance) return
  if (!geocoder) {
    console.log('[HomeMap] geocoder 未就绪,等待...')
    setTimeout(() => locate(city), 200)
    return
  }
  console.log('[HomeMap] 正在定位:', city, 'geocoder:', typeof geocoder.getLocation)
  const timeoutId = setTimeout(() => {
    console.warn('[HomeMap] Geocoder 回调超时(5s),改用静态坐标')
    fallbackLocate(city)
  }, 5000)
  try {
    geocoder.getLocation(city, (status: string, result: any) => {
      clearTimeout(timeoutId)
      console.log('[HomeMap] geocoder result:', status, JSON.stringify(result))
      if (status === 'complete' && result?.geocodes?.length) {
        const { lng, lat } = result.geocodes[0].location
        mapInstance.setCenter([lng, lat])
        mapInstance.setZoom(11)
        if (marker) {
          marker.setPosition([lng, lat])
          marker.setLabel({ content: `📍 ${city}`, direction: 'top' })
        } else {
          marker = new window.AMap.Marker({
            position: [lng, lat],
            label: { content: `📍 ${city}`, direction: 'top' },
          })
          marker.setMap(mapInstance)
        }
      } else {
        console.warn('[HomeMap] 定位失败:', status, result?.info)
        fallbackLocate(city)
      }
    })
  } catch (e) {
    clearTimeout(timeoutId)
    console.error('[HomeMap] geocoder 调用异常:', e)
    fallbackLocate(city)
  }
}

